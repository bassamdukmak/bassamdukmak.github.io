const ARABIC: Record<string, string> = {
  ...BASE_ARABIC,
  ...MANUAL_ARABIC,
};

const ARABIC_MARKS = /[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED]/g;
const EMBEDDED_LTR =
  /(?:https?:\/\/[^\s،؛]+|[\w.+-]+@[\w.-]+\.[A-Za-z]{2,}|@[A-Za-z0-9_]+|AED\s[\d,]+|£[\d,]+|\$[\d,]+|Google Analytics|Meta Pixel|UTM|gclid|fbclid)/g;
const ARABIC_FIXTURE_DATE = new Intl.DateTimeFormat("ar-AE-u-nu-latn", {
  weekday: "long",
  day: "numeric",
  month: "long",
  year: "numeric",
  timeZone: "UTC",
});

function prepareArabic(value: string) {
  return value
    .normalize("NFC")
    .replace(ARABIC_MARKS, "")
    .replace(EMBEDDED_LTR, (token) => `\u2066${token}\u2069`);
}

function translated(value: string) {
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const key = value.trim();
  if (!key) return value;

  const calendarIndex = key.match(/^(Round|Week)\s+(\d+)$/);
  if (calendarIndex) {
    const label = calendarIndex[1] === "Round" ? "الدور" : "الأسبوع";
    return `${leading}${label} ${calendarIndex[2]}${trailing}`;
  }

  const fixtureSummary = key.match(/^(\d+)\s+fixtures · Two rounds$/);
  if (fixtureSummary) {
    return `${leading}${fixtureSummary[1]} مباراة · ذهاب وإياب${trailing}`;
  }

  const exact = ARABIC[key];
  if (exact) return `${leading}${prepareArabic(exact)}${trailing}`;

  const retrySuffix = " Please retry in a moment.";
  if (key.endsWith(retrySuffix)) {
    const message = ARABIC[key.slice(0, -retrySuffix.length)];
    if (message) {
      return `${leading}${prepareArabic(message)} يرجى المحاولة مرة أخرى بعد قليل.${trailing}`;
    }
  }

  return value;
}

function translatedTextNode(node: Text) {
  const parent = node.parentElement;
  const key = node.data.trim();
  if (parent?.closest("#fixtures") && (key === "Home" || key === "Away")) {
    return key === "Home" ? "على أرضنا" : "خارج أرضنا";
  }
  const dateTime = parent?.tagName === "TIME" ? parent.getAttribute("datetime") : null;
  const isoDate = dateTime?.slice(0, 10);
  if (isoDate && /^\d{4}-\d{2}-\d{2}$/.test(isoDate)) {
    return ARABIC_FIXTURE_DATE.format(new Date(`${isoDate}T00:00:00Z`));
  }
  return translated(node.data);
}

function applyArabic(root: Document | HTMLElement) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes: Text[] = [];
  while (walker.nextNode()) nodes.push(walker.currentNode as Text);
  nodes.forEach((node) => {
    const next = translatedTextNode(node);
    if (next !== node.data) node.data = next;
  });

  root.querySelectorAll<HTMLElement>("[placeholder], [aria-label], [title], [alt]").forEach((element) => {
    ["placeholder", "aria-label", "title", "alt"].forEach((attribute) => {
      const value = element.getAttribute(attribute);
      if (!value) return;
      const next = translated(value);
      if (next !== value) element.setAttribute(attribute, next);
    });
  });
}

function languageUrl(arabic: boolean) {
  const url = new URL(window.location.href);
  if (arabic) url.searchParams.set("lang", "ar");
  else url.searchParams.delete("lang");
  return `${url.pathname}${url.search}${url.hash}`;
}

export default function LanguageController() {
  useEffect(() => {
    const arabic = new URLSearchParams(window.location.search).get("lang") === "ar";
    document.documentElement.lang = arabic ? "ar" : "en";
    document.documentElement.dir = arabic ? "rtl" : "ltr";
    document.body.classList.toggle("is-arabic", arabic);

    const toggle = document.querySelector<HTMLAnchorElement>("[data-language-toggle]");
    if (toggle) {
      toggle.href = languageUrl(!arabic);
      toggle.textContent = arabic ? "EN" : "العربية";
      toggle.setAttribute("aria-label", arabic ? "Switch to English" : "التبديل إلى العربية");
    }

    if (!arabic) return;
    document.title = translated(document.title);
    applyArabic(document.body);

    const observer = new MutationObserver((mutations) => {
      mutations.forEach((mutation) => {
        if (mutation.type === "characterData" && mutation.target.parentElement) {
          applyArabic(mutation.target.parentElement);
        }
        mutation.addedNodes.forEach((node) => {
          if (node.nodeType === Node.TEXT_NODE && node.parentElement) applyArabic(node.parentElement);
          else if (node instanceof HTMLElement) applyArabic(node);
        });
      });
    });
    observer.observe(document.body, {
      characterData: true,
      childList: true,
      subtree: true,
    });

    function preserveArabic(event: MouseEvent) {
      const anchor = (event.target as Element | null)?.closest<HTMLAnchorElement>("a[href]");
      if (!anchor || anchor.hasAttribute("data-language-toggle")) return;
      const url = new URL(anchor.href, window.location.href);
      if (url.origin !== window.location.origin) return;
      if (url.searchParams.get("lang") === "ar") return;
      event.preventDefault();
      url.searchParams.set("lang", "ar");
      window.location.assign(`${url.pathname}${url.search}${url.hash}`);
    }
    document.addEventListener("click", preserveArabic, true);

    return () => {
      observer.disconnect();
      document.removeEventListener("click", preserveArabic, true);
    };
  }, []);

  return null;
}
